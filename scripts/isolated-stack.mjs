#!/usr/bin/env node
// A second, throwaway copy of the application for browser tests and failure drills.
//
// It is a separate Compose project (its own containers, network and database volume) on its
// own ports, started from its own environment file. It never reads .env, so no API key in
// .env can reach it: the engine is the rule-based one and every provider key is empty.
// Nothing here can touch the default project ("opspilot") or its data.
//
//   node scripts/isolated-stack.mjs up        build, start, wait until healthy
//   node scripts/isolated-stack.mjs down      stop and remove it, including its volume
//   node scripts/isolated-stack.mjs status
//   node scripts/isolated-stack.mjs compose <args…>   any other docker compose command against it
import { spawnSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const PROJECT = 'opspilot-isolated';
export const ENV_FILE = join(ROOT, '.env.isolated'); // ignored by git (.env.*)
export const PORTS = { web: 13000, api: 14000, ai: 18000, postgres: 15432, redis: 16379 };
export const URLS = { web: `http://localhost:${PORTS.web}`, api: `http://localhost:${PORTS.api}`, ai: `http://localhost:${PORTS.ai}` };

const secret = () => randomBytes(32).toString('hex');

/** Written once and reused, so a restart of the stack keeps working with the data it has. */
export function ensureEnv() {
  if (existsSync(ENV_FILE)) return;
  const lines = [
    '# Generated by scripts/isolated-stack.mjs for the throwaway test stack. Not used by anything else.',
    `JWT_SECRET=${secret()}`,
    `INTERNAL_SERVICE_TOKEN=${secret()}`,
    `ENCRYPTION_KEY=${secret()}`,
    'POSTGRES_PASSWORD=opspilot',
    'SEED_DEMO_DATA=true',
    // No model, no cost: the rule-based engine, and no key for any provider.
    'AI_PROVIDER=deterministic',
    'ANTHROPIC_API_KEY=',
    'OPENAI_API_KEY=',
    'EMBEDDING_PROVIDER=local',
    'OTEL_ENABLED=false',
    `WEB_ORIGIN=${URLS.web}`,
    `HOST_PORT_WEB=${PORTS.web}`,
    `HOST_PORT_API=${PORTS.api}`,
    `HOST_PORT_AI=${PORTS.ai}`,
    `HOST_PORT_POSTGRES=${PORTS.postgres}`,
    `HOST_PORT_REDIS=${PORTS.redis}`,
    // The drills start many investigations in a row.
    'INVESTIGATION_DAILY_LIMIT=0',
    '',
  ];
  writeFileSync(ENV_FILE, lines.join('\n'), { mode: 0o600 });
}

/** The generated secrets, for checking that none of them appears in a log. Never printed. */
export function secrets() {
  return Object.fromEntries(
    readFileSync(ENV_FILE, 'utf8')
      .split('\n')
      .map((l) => l.split('='))
      .filter(([k]) => ['JWT_SECRET', 'INTERNAL_SERVICE_TOKEN', 'ENCRYPTION_KEY'].includes(k)),
  );
}

// The shell's own variables win over an env file in Compose. Anything that selects a model or
// carries a key is removed, so an exported ANTHROPIC_API_KEY cannot leak into this stack.
function cleanEnv(extra = {}) {
  const env = { ...process.env };
  for (const key of Object.keys(env)) {
    if (/^(AI_PROVIDER|ANTHROPIC_|OPENAI_|OLLAMA_|EMBEDDING_PROVIDER|HOST_PORT_|JWT_SECRET|INTERNAL_SERVICE_TOKEN|ENCRYPTION_KEY|POSTGRES_PASSWORD|WEB_ORIGIN|SEED_DEMO_DATA|COMPOSE_PROJECT_NAME|COMPOSE_FILE)/.test(key)) delete env[key];
  }
  return { ...env, ...extra };
}

/** Runs `docker compose` against the isolated project. Returns { status, stdout, stderr }. */
export function compose(args, { capture = false, env = {} } = {}) {
  ensureEnv();
  const res = spawnSync('docker', ['compose', '-p', PROJECT, '--env-file', ENV_FILE, '--profile', 'app', ...args], {
    cwd: ROOT,
    env: cleanEnv(env),
    encoding: 'utf8',
    stdio: capture ? ['ignore', 'pipe', 'pipe'] : 'inherit',
    maxBuffer: 64 * 1024 * 1024,
  });
  return { status: res.status ?? 1, stdout: res.stdout ?? '', stderr: res.stderr ?? '' };
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const [command = 'status', ...rest] = process.argv.slice(2);
  let status = 0;
  if (command === 'up') {
    status = compose(['up', '-d', '--build', '--wait', '--wait-timeout', '420', ...rest]).status;
    if (status === 0) console.log(`\nIsolated stack is up: ${URLS.web} (API ${URLS.api}). Remove it with: npm run isolated:down`);
  } else if (command === 'down') {
    // -v removes this project's volume only; the default project's data is another volume.
    status = compose(['down', '-v', '--remove-orphans', ...rest]).status;
  } else if (command === 'status') {
    status = compose(['ps', ...rest]).status;
  } else if (command === 'compose') {
    status = compose(rest).status;
  } else {
    console.error('usage: isolated-stack.mjs up | down | status | compose <args…>');
    status = 2;
  }
  process.exit(status);
}
