// Generates the TypeScript and Python representations of the shared contracts from the JSON
// files in contracts/. Run with `npm run contracts`; CI runs it and fails if anything changes
// (`npm run contracts:check`), so neither side can drift from the definition.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (name) => {
  const { $comment: _c, ...data } = JSON.parse(readFileSync(join(ROOT, 'contracts', name), 'utf8'));
  return data;
};
const effects = read('action-effects.json');
const enums = read('enums.json');
const guardrails = read('guardrails.json');

const HEADER = 'GENERATED by scripts/contracts.mjs from contracts/*.json. Do not edit: change the JSON and run `npm run contracts`.';
const pascal = (s) => s[0].toUpperCase() + s.slice(1);
const singular = (s) => (s.endsWith('ses') ? s.slice(0, -2) : s.endsWith('s') ? s.slice(0, -1) : s);
const snake = (s) => s.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);

// ── TypeScript ──
const ts = [`// ${HEADER}`, ''];
for (const [name, values] of Object.entries(enums)) {
  const constant = snake(name).toUpperCase();
  ts.push(`export const ${constant} = ${JSON.stringify(values)} as const;`);
  ts.push(`export type ${pascal(singular(name))} = (typeof ${constant})[number];`, '');
}
ts.push(`export const GUARDRAIL_LIMITS = ${JSON.stringify(guardrails, null, 2)} as const;`, '');
ts.push(`export const ACTION_EFFECT_RULES = ${JSON.stringify(effects, null, 2)} as const;`, '');
const tsOut = `${ts.join('\n')}`;

// ── Python ──
const py = [`"""${HEADER}"""`, '', 'from typing import Any, Literal', ''];
for (const [name, values] of Object.entries(enums)) {
  const constant = snake(name).toUpperCase();
  py.push(`${pascal(singular(name))} = Literal[${values.map((v) => JSON.stringify(v)).join(', ')}]`);
  py.push(`${constant}: tuple[str, ...] = (${values.map((v) => JSON.stringify(v)).join(', ')}${values.length === 1 ? ',' : ''})`, '');
}
const pyLiteral = (value) => JSON.stringify(value, null, 4).replace(/\btrue\b/g, 'True').replace(/\bfalse\b/g, 'False').replace(/\bnull\b/g, 'None');
py.push(`GUARDRAIL_LIMITS: dict[str, Any] = ${pyLiteral(guardrails)}`, '');
py.push(`ACTION_EFFECT_RULES: dict[str, Any] = ${pyLiteral(effects)}`, '');
const pyOut = py.join('\n');

const targets = [
  [join(ROOT, 'apps/api/src/generated/contracts.ts'), tsOut],
  [join(ROOT, 'apps/web/src/lib/generated/contracts.ts'), tsOut],
  [join(ROOT, 'services/ai/app/generated/contracts.py'), pyOut],
];
for (const [path, content] of targets) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
}
const init = join(ROOT, 'services/ai/app/generated/__init__.py');
writeFileSync(init, '');
console.log(`contracts: wrote ${targets.length} files from ${['action-effects.json', 'enums.json', 'guardrails.json'].join(', ')}`);
