"""Exports the contracts this service is the authority for, into contracts/ at the repository root.

    uv run python -m app.contracts            # write contracts/report.schema.json and contracts/tools.json
    uv run python -m app.contracts --check    # exit 1 if either file is out of date (CI)

report.schema.json  The investigation report as this service sends it (JSON Schema of
                    schemas.InvestigationReport, camelCase). The API's Zod schema is checked
                    against it by apps/api/tests/contract.test.ts.
tools.json          Every tool the agent can call: its HTTP method and path under /api/v1/tools,
                    the query or body parameters this service sends, and the top-level response
                    fields the evidence extractors read. The API is checked against it.

Both files are derived from the code that is actually used (the pydantic models, the tool
registry, the request mapping and the extractors' source), so they cannot describe something
the service does not do.
"""

from __future__ import annotations

import inspect
import json
import re
import sys
import types
from pathlib import Path
from typing import Any, Union, get_args, get_origin

from pydantic import BaseModel

from .evidence import EvidenceStore
from .schemas import InvestigationReport
from .tools import TOOLS, ToolSpec, _request_for

CONTRACTS = Path(__file__).resolve().parents[3] / "contracts"

#: Response fields read outside the evidence extractors (by the graph and by coverage tracking).
READ_ELSEWHERE = {"list_services": ["services"], "get_log_histogram": ["buckets"]}


def _dummy(annotation: Any) -> Any:
    """A value of the right type for a tool argument, so that every parameter is sent."""
    origin = get_origin(annotation)
    if origin in (Union, types.UnionType):
        return _dummy(next(a for a in get_args(annotation) if a is not type(None)))
    if origin is list:
        return [_dummy(get_args(annotation)[0])]
    if annotation is bool:
        return True
    if annotation is int:
        return 1
    return "x"


def tool_contract(spec: ToolSpec) -> dict[str, Any]:
    args: BaseModel = spec.args.model_validate({name: _dummy(field.annotation) for name, field in spec.args.model_fields.items()})
    path, params, body = _request_for(spec, args)
    placeholders = re.findall(r"{(\w+)}", spec.path)
    extractor = getattr(EvidenceStore, f"_from_{spec.name}", None)
    reads = sorted(set(re.findall(r'\br\.get\("(\w+)"|\br\["(\w+)"\]', inspect.getsource(extractor)))) if extractor else []
    return {
        "name": spec.name,
        "method": spec.method,
        "path": spec.path,
        "pathParameters": placeholders,
        "query": sorted(params or {}),
        "body": sorted(body or {}),
        "reads": sorted({a or b for a, b in reads} | set(READ_ELSEWHERE.get(spec.name, []))),
    }


def build() -> dict[str, str]:
    report = InvestigationReport.model_json_schema(by_alias=True, mode="serialization")
    tools = {"basePath": "/api/v1/tools", "tools": [tool_contract(t) for t in TOOLS]}
    note = "GENERATED by `uv run python -m app.contracts` in services/ai. Do not edit."
    return {
        "report.schema.json": json.dumps({"$comment": note, **report}, indent=2) + "\n",
        "tools.json": json.dumps({"$comment": note, **tools}, indent=2) + "\n",
    }


def stale() -> list[str]:
    return [name for name, content in build().items() if not (CONTRACTS / name).exists() or (CONTRACTS / name).read_text() != content]


def main() -> None:
    if "--check" in sys.argv:
        out_of_date = stale()
        if out_of_date:
            print(f"Out of date: {', '.join(out_of_date)}. Run `npm run contracts`.", file=sys.stderr)
            sys.exit(1)
        print("contracts: report.schema.json and tools.json are up to date")
        return
    for name, content in build().items():
        (CONTRACTS / name).write_text(content)
    print("contracts: wrote report.schema.json and tools.json")


if __name__ == "__main__":
    main()
