/**
 * Exports the API response contracts (src/contracts/api.ts) for the web app:
 *
 *   contracts/api.schema.json                  JSON Schema of every response type
 *   apps/web/src/lib/generated/api.ts          TypeScript types generated from that schema
 *
 * Run through `npm run contracts`. CI regenerates both and fails if either would change, so
 * the web app's types cannot drift from what the API defines. No dependencies beyond Zod: the
 * emitter below covers the JSON Schema that Zod produces for these contracts.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { z } from 'zod';
import { API_CONTRACT } from '../src/contracts/api';

type Schema = {
  type?: string | string[];
  properties?: Record<string, Schema>;
  required?: string[];
  items?: Schema;
  enum?: unknown[];
  const?: unknown;
  anyOf?: Schema[];
  additionalProperties?: boolean | Schema;
  description?: string;
};

const ROOT = join(__dirname, '../../..');
const HEADER = 'GENERATED by apps/api/scripts/export-api-contract.ts from apps/api/src/contracts/api.ts. Do not edit: change the contract and run `npm run contracts`.';

const schemas = Object.fromEntries(
  Object.entries(API_CONTRACT).map(([name, schema]) => {
    // "output": what the API sends, after defaults are applied.
    const { $schema: _s, ...rest } = z.toJSONSchema(schema, { io: 'output', unrepresentable: 'any' }) as Schema & { $schema?: string };
    return [name, rest as Schema];
  }),
);

const literal = (v: unknown) => (typeof v === 'string' ? `'${v.replace(/'/g, "\\'")}'` : String(v));
const key = (k: string) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : `'${k}'`);

function emit(s: Schema, indent: string): string {
  if (s.const !== undefined) return literal(s.const);
  if (s.enum) return s.enum.map(literal).join(' | ');
  if (s.anyOf) {
    const parts = [...new Set(s.anyOf.map((a) => emit(a, indent)))];
    return parts.map((p) => (p.includes(' | ') && parts.length > 1 ? `(${p})` : p)).join(' | ');
  }
  if (Array.isArray(s.type)) return s.type.map((t) => emit({ ...s, type: t }, indent)).join(' | ');
  switch (s.type) {
    case 'string':
      return 'string';
    case 'number':
    case 'integer':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'null':
      return 'null';
    case 'array': {
      const item = emit(s.items ?? {}, indent);
      return /[ |{]/.test(item) && !item.startsWith('{') ? `(${item})[]` : `${item}[]`;
    }
    case 'object': {
      const props = Object.entries(s.properties ?? {});
      if (!props.length) {
        const extra = typeof s.additionalProperties === 'object' ? emit(s.additionalProperties, indent) : 'unknown';
        return `Record<string, ${extra}>`;
      }
      const required = new Set(s.required ?? []);
      const inner = `${indent}  `;
      const lines = props.map(([name, prop]) => {
        const doc = prop.description && prop.description !== 'ISO-8601 timestamp' ? `${inner}/** ${prop.description} */\n` : '';
        return `${doc}${inner}${key(name)}${required.has(name) ? '' : '?'}: ${emit(prop, inner)};`;
      });
      return `{\n${lines.join('\n')}\n${indent}}`;
    }
    default:
      return 'unknown';
  }
}

const body = Object.entries(schemas)
  .map(([name, schema]) => (schema.type === 'object' && schema.properties ? `export interface ${name} ${emit(schema, '')}` : `export type ${name} = ${emit(schema, '')};`))
  .join('\n\n');
const ts = `// ${HEADER}\n\n${body}\n\n/** A page of results, as every list endpoint returns it. */\nexport interface Paged<T> {\n  data: T[];\n  meta: PageMeta;\n}\n`;

const write = (path: string, content: string) => {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
};
write(join(ROOT, 'contracts/api.schema.json'), `${JSON.stringify({ $comment: HEADER, $defs: schemas }, null, 2)}\n`);
write(join(ROOT, 'apps/web/src/lib/generated/api.ts'), ts);
process.stdout.write(`contracts: wrote api.schema.json and the web app's API types (${Object.keys(schemas).length} types)\n`);
